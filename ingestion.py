from dotenv import load_dotenv
from langchain_chroma import Chroma
from langchain_openai import OpenAIEmbeddings
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_core.documents import Document
from tavily import TavilyClient

load_dotenv()

urls = [
    "https://lilianweng.github.io/posts/2023-06-23-agent/",
    "https://lilianweng.github.io/posts/2023-03-15-prompt-engineering/",
    "https://lilianweng.github.io/posts/2023-10-25-adv-attack-llm/",
]

# Initialize Tavily client (automatically picks up TAVILY_API_KEY from your .env file)
tavily_client = TavilyClient()

# Extract content from all URLs in a single batch request
response = tavily_client.extract(urls=urls)

# Convert Tavily's extraction results directly into LangChain Document objects
docs_list = [
    Document(
        page_content=result["raw_content"],
        metadata={"source": result["url"]}
    )
    for result in response["results"]
]

text_splitter = RecursiveCharacterTextSplitter.from_tiktoken_encoder(
    chunk_size=250, chunk_overlap=0
)
doc_splits = text_splitter.split_documents(docs_list)

